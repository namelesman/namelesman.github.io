let createNewPacman = () => {
    pacman = new Pacman(
        oneBlockSize,
        oneBlockSize,
        oneBlockSize,
        oneBlockSize,
        oneBlockSize / 5
    );
};

let gameLoop = () => {
    update();
    draw();
};

let gameInterval = setInterval(gameLoop, 1000 / fps);

let restartPacmanAndGhosts = () => {
    createNewPacman();
    createGhosts();
};

let onGhostCollision = () => {
    lives--;
    if (lives <= 0) {
        lives = 0;
        gameState = "over";
        return;
    }
    restartPacmanAndGhosts();
};

let hasFoodLeft = () => map.some((row) => row.includes(2));

let resetGame = () => {
    map = initialMap.map((row) => row.slice());
    score = 0;
    lives = 3;
    gameState = "playing";
    restartPacmanAndGhosts();
};

// Linha 10 tem passagem nas duas bordas: quem sai por um lado entra pelo outro
let wrapTunnel = (entity) => {
    let mapWidth = map[0].length * oneBlockSize;
    if (entity.x < -oneBlockSize / 2) entity.x += mapWidth;
    else if (entity.x > mapWidth - oneBlockSize / 2) entity.x -= mapWidth;
};

let update = () => {
    if (gameState != "playing") return;
    pacman.moveProcess();
    pacman.eat();
    if (!hasFoodLeft()) {
        gameState = "won";
        return;
    }
    updateGhosts();
    if (pacman.checkGhostCollision(ghosts)) {
        onGhostCollision();
    }
};

let drawFoods = () => {
    for (let i = 0; i < map.length; i++) {
        for (let j = 0; j < map[0].length; j++) {
            if (map[i][j] == 2) {
                createRect(
                    j * oneBlockSize + oneBlockSize / 3,
                    i * oneBlockSize + oneBlockSize / 3,
                    oneBlockSize / 3,
                    oneBlockSize / 3,
                    "#FEB897"
                );
            }
        }
    }
};

let drawRemainingLives = () => {
    canvasContext.font = "20px Emulogic";
    canvasContext.fillStyle = "white";
    canvasContext.fillText("Lives: ", 220, oneBlockSize * (map.length + 1));

    for (let i = 0; i < lives; i++) {
        canvasContext.drawImage(
            pacmanFrames,
            2 * oneBlockSize,
            0,
            oneBlockSize,
            oneBlockSize,
            350 + i * oneBlockSize,
            oneBlockSize * map.length + 2,
            oneBlockSize,
            oneBlockSize
        );
    }
};

let drawScore = () => {
    canvasContext.font = "20px Emulogic";
    canvasContext.fillStyle = "white";
    canvasContext.fillText(
        "Score: " + score,
        0,
        oneBlockSize * (map.length + 1)
    );
};

let draw = () => {
    canvasContext.clearRect(0, 0, canvas.width, canvas.height);
    createRect(0, 0, canvas.width, canvas.height, "black");
    drawWalls();
    drawFoods();
    drawGhosts();
    pacman.draw();
    drawScore();
    drawRemainingLives();
    if (gameState != "playing") drawEndScreen();
};

let drawEndScreen = () => {
    let centerX = (map[0].length * oneBlockSize) / 2;
    let centerY = (map.length * oneBlockSize) / 2;
    canvasContext.fillStyle = "rgba(0, 0, 0, 0.75)";
    canvasContext.fillRect(0, 0, canvas.width, map.length * oneBlockSize);
    canvasContext.textAlign = "center";
    canvasContext.fillStyle = gameState == "won" ? "#FFE600" : "#FF3B3B";
    canvasContext.font = "bold 40px Emulogic, monospace";
    canvasContext.fillText(gameState == "won" ? texts.won : texts.over, centerX, centerY - 30);
    canvasContext.fillStyle = "white";
    canvasContext.font = "20px Emulogic, monospace";
    canvasContext.fillText(texts.score + score, centerX, centerY + 10);
    canvasContext.font = "14px Emulogic, monospace";
    canvasContext.fillText(texts.again, centerX, centerY + 50);
    canvasContext.fillText(texts.exit, centerX, centerY + 72);
    canvasContext.textAlign = "start";
};

let drawWalls = () => {
    for (let i = 0; i < map.length; i++) {
        for (let j = 0; j < map[0].length; j++) {
            if (map[i][j] == 1) {
                createRect(
                    j * oneBlockSize,
                    i * oneBlockSize,
                    oneBlockSize,
                    oneBlockSize,
                    "#342DCA"
                );
                if (j > 0 && map[i][j - 1] == 1) {
                    createRect(
                        j * oneBlockSize,
                        i * oneBlockSize + wallOffset,
                        wallSpaceWidth + wallOffset,
                        wallSpaceWidth,
                        wallInnerColor
                    );
                }

                if (j < map[0].length - 1 && map[i][j + 1] == 1) {
                    createRect(
                        j * oneBlockSize + wallOffset,
                        i * oneBlockSize + wallOffset,
                        wallSpaceWidth + wallOffset,
                        wallSpaceWidth,
                        wallInnerColor
                    );
                }

                if (i < map.length - 1 && map[i + 1][j] == 1) {
                    createRect(
                        j * oneBlockSize + wallOffset,
                        i * oneBlockSize + wallOffset,
                        wallSpaceWidth,
                        wallSpaceWidth + wallOffset,
                        wallInnerColor
                    );
                }

                if (i > 0 && map[i - 1][j] == 1) {
                    createRect(
                        j * oneBlockSize + wallOffset,
                        i * oneBlockSize,
                        wallSpaceWidth,
                        wallSpaceWidth + wallOffset,
                        wallInnerColor
                    );
                }
            }
        }
    }
};

let createGhosts = () => {
    ghosts = [];
    for (let i = 0; i < ghostCount * 2; i++) {
        let newGhost = new Ghost(
            9 * oneBlockSize + (i % 2 == 0 ? 0 : 1) * oneBlockSize,
            10 * oneBlockSize + (i % 2 == 0 ? 0 : 1) * oneBlockSize,
            oneBlockSize,
            oneBlockSize,
            pacman.speed / 2,
            ghostImageLocations[i % 4].x,
            ghostImageLocations[i % 4].y,
            124,
            116,
            6 + i
        );
        ghosts.push(newGhost);
    }
};

createNewPacman();
createGhosts();
gameLoop();

window.addEventListener("keydown", (event) => {
    let k = event.keyCode;
    if (gameState != "playing") {
        if (k == 13 || k == 32) resetGame(); // Enter ou espaço
        return;
    }
    setTimeout(() => {
        if (k == 37 || k == 65) {
            // left arrow or a
            pacman.nextDirection = DIRECTION_LEFT;
        } else if (k == 38 || k == 87) {
            // up arrow or w
            pacman.nextDirection = DIRECTION_UP;
        } else if (k == 39 || k == 68) {
            // right arrow or d
            pacman.nextDirection = DIRECTION_RIGHT;
        } else if (k == 40 || k == 83) {
            // bottom arrow or s
            pacman.nextDirection = DIRECTION_BOTTOM;
        }
    }, 1);
});
